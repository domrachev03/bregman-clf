"""Statistics of the comparison with per-face CBF QPs (sweep `configs/cbf_comparison.yaml`): step
rates of constraint violations, trials with any violation, median final error, median torque total
variation on QP-solved steps. Most pairs of trials tie at zero violations, so the comparison uses
an exact sign test on the non-tied pairs, Holm-corrected over the three baselines.

    python experiments/manipulator/cbf_comparison_stats.py

Reads the summary of a fresh sweep in runs/cbf_comparison/ if there is one, else the stored
results/manipulator/cbf_comparison_summary.parquet; writes cbf_comparison_stats.json and
cbf_comparison_numbers.tex (LaTeX macros of the numbers quoted in the text) to results/manipulator/.
"""

from __future__ import annotations

import json

import numpy as np
import pandas as pd
from _paths import RESULTS, summary_path
from scipy import stats

INSIDE = ("joint_stress", "keep_in_box", "keep_in_ellipsoid", "fast_motions")
MAIN = "bregman_id_level"
VIOL = ["qpos_violation_rate_tol", "qvel_violation_rate_tol", "keep_in_violation_rate_tol"]
MACRO = {"bregman_id_level": "Ours", "clf_aecbf": "Btwo", "tsid_cbf": "Boneplus", "tsid": "Bone"}


def holm(pvalues) -> np.ndarray:
    """Holm-Bonferroni adjusted p-values (same order as the input)."""
    p = np.asarray(pvalues, dtype=float)
    order = np.argsort(p)
    m = p.size
    adj = np.empty(m)
    running = 0.0
    for rank, i in enumerate(order):
        running = max(running, (m - rank) * p[i])
        adj[i] = min(1.0, running)
    return adj


def pct(x: float) -> str:
    return "0" if x == 0 else (f"{100 * x:.1f}" if x >= 1e-3 else "{<}0.1")


def main():
    df = pd.read_parquet(summary_path("cbf_comparison"))
    df["variant"] = df["scenario"].str.removeprefix("iiwa_constraints_")
    df = df[df.variant.isin(INSIDE)]
    df["fe_mm"] = 1000.0 * df["final_error_proj"]
    out = {"n_seeds": int(df.seed.nunique()), "n_variants": int(df.variant.nunique())}
    for label in df.method.unique():
        d = df[df.method == label]
        out[label] = dict(n=len(d), keepin=float(d.keep_in_violation_rate_tol.mean()),
                          keepin_trials=int(d.keep_in_violated_trial.sum()),
                          viol=float(d[VIOL].sum(axis=1).mean()), fb=float(d.fallback_rate.mean()),
                          viol_trials=int((d[VIOL].sum(axis=1) > 0).sum()),
                          err_med=float(d.fe_mm.median()),
                          tv=float(d.torque_total_variation_solved.median()))
    base = df[df.method == MAIN].set_index(["variant", "seed"])
    labels = [m for m in MACRO if m != MAIN]
    p = []
    for label in labels:
        other = df[df.method == label].set_index(["variant", "seed"])
        idx = base.index.intersection(other.index)
        diff = other.loc[idx, VIOL].sum(axis=1) - base.loc[idx, VIOL].sum(axis=1)
        nz = diff[diff != 0]
        p.append(stats.binomtest(int((nz > 0).sum()), len(nz)).pvalue if len(nz) else 1.0)
    for label, raw, adj in zip(labels, p, holm(p)):
        out[label]["p_viol"], out[label]["p_viol_holm"] = float(raw), float(adj)
    (RESULTS / "cbf_comparison_stats.json").write_text(json.dumps(out, indent=1))
    lines = ["% Generated by cbf_comparison_stats.py.",
             rf"\newcommand{{\NEtwoInN}}{{{out[MAIN]['n']}}}",
             rf"\newcommand{{\NEtwoInScen}}{{{out['n_variants']}}}"]
    for label, m in MACRO.items():
        r = out[label]
        lines += [rf"\newcommand{{\NEtwoIn{m}Keepin}}{{{pct(r['keepin'])}}}",
                  rf"\newcommand{{\NEtwoIn{m}KeepinTrials}}{{{r['keepin_trials']}}}",
                  rf"\newcommand{{\NEtwoIn{m}Err}}{{{r['err_med']:.2f}}}",
                  rf"\newcommand{{\NEtwoIn{m}Viol}}{{{pct(r['viol'])}}}",
                  rf"\newcommand{{\NEtwoIn{m}ViolTrials}}{{{r['viol_trials']}}}",
                  rf"\newcommand{{\NEtwoIn{m}TV}}{{{r['tv']:.0f}}}"]
        if label != MAIN:
            lines.append(rf"\newcommand{{\NEtwoIn{m}P}}{{{r['p_viol_holm']:.2g}}}")
    (RESULTS / "cbf_comparison_numbers.tex").write_text("\n".join(lines) + "\n")
    print("\n".join(lines))
    print(json.dumps({k: out[k] for k in MACRO}, indent=1))


if __name__ == "__main__":
    main()
